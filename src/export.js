export const encodeHash = inp => '#c=' + encodeURIComponent(JSON.stringify(inp))

// -> inputs object, or null if the hash is missing or unreadable.
export function decodeHash(hash) {
  if (!hash.startsWith('#c=')) return null
  try { const v = JSON.parse(decodeURIComponent(hash.slice(3))); return v && typeof v === 'object' ? v : null }
  catch { return null }
}
